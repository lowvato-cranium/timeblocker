import fs from "fs";
import path from "path";
import Database from "better-sqlite3";
import { drizzle } from "drizzle-orm/better-sqlite3";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import { DATA_DIR, MIGRATIONS_DIR } from "../config.js";
import * as schema from "./schema.js";

fs.mkdirSync(DATA_DIR, { recursive: true });
const dbPath = path.join(DATA_DIR, "timeblocker.db");

const sqlite = new Database(dbPath);
sqlite.pragma("journal_mode = WAL");
sqlite.pragma("foreign_keys = ON");

export const db = drizzle(sqlite, { schema });

// Migrations are plain .sql files generated by `npm run db:generate` and
// checked into git — applying them here means a fresh checkout just works.
migrate(db, { migrationsFolder: MIGRATIONS_DIR });
